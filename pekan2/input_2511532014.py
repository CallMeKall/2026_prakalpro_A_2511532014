#Program untuk menghitung luas persegi panjang
#Program ini menggunakan fungsi input() untuk menerima input dari pengguna
panjang_2014 = input("Masukkan panjang persegi panjang: ")
lebar_2014 = input("Masukkan lebar persegi panjang: ")
luas_2014 = int(panjang_2014) * int(lebar_2014)
print("Luas =", luas_2014)